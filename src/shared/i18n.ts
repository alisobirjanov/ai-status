/** What Windows asks for. The words are Russian for Russian, English otherwise. */
const preferred = navigator.language || "en";
const isRussian = preferred.toLowerCase().startsWith("ru");
const table: Record<Key, string> = isRussian ? russian : english;

/**
 * The locale dates and times are written in: the language of the words
 * around them, on the reader's own clock — English words for somebody whose
 * Windows is in Uzbek still keep its 24-hour time.
 */
export const locale: string = isRussian || preferred.toLowerCase().startsWith("en") ? preferred : englishOnOwnClock(preferred);

function englishOnOwnClock(tag: string): string {
  try {
    const cycle = new Intl.DateTimeFormat(tag, { hour: "numeric" }).resolvedOptions().hourCycle;
    return cycle ? `en-u-hc-${cycle}` : "en";
  } catch {
    return "en";
  }
}

export function t(key: Key, ...args: string[]): string {
  return table[key].replace(/\{(\d+)\}/g, (_, index: string) => args[Number(index)] ?? "");
}

export type { Key as StringKey };
