export const locale: string = navigator.language || "en";
const isRussian = locale.toLowerCase().startsWith("ru");
const table: Record<Key, string> = isRussian ? russian : english;

export function t(key: Key, ...args: string[]): string {
  return table[key].replace(/\{(\d+)\}/g, (_, index: string) => args[Number(index)] ?? "");
}

export type { Key as StringKey };
